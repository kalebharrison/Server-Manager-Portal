        smtpPass: config.smtpPass ? secretMask : '',
        smtpFrom: config.smtpFrom || '',
        smtpSecure: !!config.smtpSecure,
        emailDaysBefore: config.emailDaysBefore || 7,
        newsletterFrequency: config.newsletterFrequency || 'disabled',
        newsletterDay: config.newsletterDay || 0,
        inactiveCleanupEnabled: !!config.inactiveCleanupEnabled,
        inactiveCleanupDays: config.inactiveCleanupDays || 90,
        publicDomain: config.publicDomain || 'https://portal.yourdomain.com',
        requestUrl: config.requestUrl || 'https://yourdomain.com',
        contactUrl: config.contactUrl || '',
        contactEmail,
        discordEnabled: !!config.discordEnabled,
        discordInviteUrl: config.discordInviteUrl || '',
        discordChatChannelLabel: config.discordChatChannelLabel || '',
        discordMediaChannelLabel: config.discordMediaChannelLabel || '',
        discordGuildId: config.discordGuildId || '',
        discordBotToken: config.discordBotToken ? secretMask : '',
        discordBotEnabled: !!config.discordBotEnabled,
        discordWebhookUrl: config.discordWebhookUrl ? secretMask : '',
        discordNotifyRequestUpdates: config.discordNotifyRequestUpdates !== false,
        discordNotifyIssueReplies: config.discordNotifyIssueReplies !== false,
        discordNotifyWatchlistAvailable: config.discordNotifyWatchlistAvailable !== false,
        discordLlmEnabled: !!config.discordLlmEnabled,
        discordLlmUrl: config.discordLlmUrl || '',
        discordLlmApiKey: config.discordLlmApiKey ? secretMask : '',
        discordLlmModel: config.discordLlmModel || 'gpt-4o-mini',
        discordMentionNl: !!config.discordMentionNl,
        discordAgentEnabled: config.discordAgentEnabled !== false,
        discordSearxngUrl: config.discordSearxngUrl || '',
