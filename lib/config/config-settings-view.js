        qcMaxStrikes: Math.max(1, Number(config.qcMaxStrikes) || 3),
        qcResearchThrottleHours: Math.max(1, Number(config.qcResearchThrottleHours) || 24),
        qcSnoozeDefaultHours: Math.max(1, Number(config.qcSnoozeDefaultHours) || 24),
        qcDiscordDigestEnabled: !!config.qcDiscordDigestEnabled,
