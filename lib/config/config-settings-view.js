export const buildConfigGetResponse = (config, { isPortalConfigured, secretMask, defaultDashboardLayout, normalizeSectionLayout }) => {
    const configured = isPortalConfigured(config);
    return {
        configured,
        settings: configured
            ? buildConfiguredSettingsPayload(config, secretMask, normalizeSectionLayout)
            : buildUnconfiguredSettingsPayload(defaultDashboardLayout),
    };
};
